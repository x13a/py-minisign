@pytest.mark.parametrize(
    "encoded_signature, prehashed",
    (
        (GO_LEGACY_SIGNATURE, False),
        (GO_PREHASHED_SIGNATURE, True),
    ),
)
def test_go_signature_vectors(encoded_signature: bytes, prehashed: bool):
    signature = Signature.from_bytes(encoded_signature)
    assert signature.is_prehashed() is prehashed
    PublicKey.from_base64(GO_PUBLIC_KEY).verify(b"test", signature)


def test_go_unencrypted_key_vector():
    secret_key = SecretKey.from_bytes(GO_UNENCRYPTED_SECRET_KEY)
    public_key = PublicKey.from_bytes(GO_UNENCRYPTED_PUBLIC_KEY)
    assert not secret_key.is_encrypted()
    assert secret_key.get_public_key().to_base64() == public_key.to_base64()


def test_go_encrypted_key_vector():
    secret_key = SecretKey.from_bytes(GO_ENCRYPTED_SECRET_KEY)
    public_key = PublicKey.from_bytes(GO_ENCRYPTED_PUBLIC_KEY)
    assert secret_key.is_encrypted()
    secret_key.decrypt("testpass")
    assert not secret_key.is_encrypted()
    assert secret_key.get_public_key().to_base64() == public_key.to_base64()


def test_go_encrypted_key_rejects_wrong_password():
    secret_key = SecretKey.from_bytes(GO_ENCRYPTED_SECRET_KEY)
    encoded = bytes(secret_key)
    with pytest.raises(Error, match="wrong password"):
        secret_key.decrypt("nope")
    assert bytes(secret_key) == encoded


@pytest.mark.parametrize("prehashed", (False, True))
def test_go_sign_roundtrip(prehashed: bool):
    secret_key = SecretKey.from_bytes(GO_UNENCRYPTED_SECRET_KEY)
    public_key = PublicKey.from_bytes(GO_UNENCRYPTED_PUBLIC_KEY)
    data = b"the quick brown fox jumps over the lazy dog"
    signature = secret_key.sign(
        data,
        prehash=prehashed,
        untrusted_comment="hello world",
        trusted_comment="file:fox.txt",
    )
    parsed = Signature.from_bytes(bytes(signature))
    assert parsed.untrusted_comment == "hello world"
    assert parsed.trusted_comment == "file:fox.txt"
    public_key.verify(data, parsed)


def test_go_sign_defaults():
    signature = SecretKey.from_bytes(GO_UNENCRYPTED_SECRET_KEY).sign(b"hi")
    assert signature.untrusted_comment == "signature from minisign secret key"
    assert signature.trusted_comment.startswith("timestamp:")


@pytest.mark.parametrize(
    "untrusted_comment, trusted_comment",
    (
        ("a\nb", None),
        (None, "a\nb"),
        (None, "foo\x01bar"),
        (None, "a" * 8200),
    ),
)
def test_go_sign_rejects_invalid_comments(
    untrusted_comment: str | None,
    trusted_comment: str | None,
):
    secret_key = SecretKey.from_bytes(GO_UNENCRYPTED_SECRET_KEY)
    with pytest.raises(ParseError):
        secret_key.sign(
            b"x",
            untrusted_comment=untrusted_comment,
            trusted_comment=trusted_comment,
        )


def test_rust_public_key_vectors():
    PublicKey.from_base64(RUST_VALID_PUBLIC_KEY)
    with pytest.raises(ParseError):
        PublicKey.from_base64(RUST_INVALID_PUBLIC_KEY)


