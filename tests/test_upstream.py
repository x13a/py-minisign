def test_rust_signature_rejects_modified_data():
    key_pair = KeyPair.generate()
    signature = key_pair.secret_key.sign(b"test")
    with pytest.raises(Error):
        key_pair.public_key.verify(b"test2", signature)


def test_rust_empty_password_roundtrip():
    key_pair = KeyPair.generate()
    key_pair.secret_key.encrypt("")
    assert key_pair.secret_key.is_encrypted()
    stored = SecretKey.from_bytes(bytes(key_pair.secret_key))
    stored.decrypt("")
    assert not stored.is_encrypted()
    key_pair.public_key.verify(b"test", stored.sign(b"test"))
